// 入口：魔棒菜单 / 悬浮球 / 两个都要 / 都不要；悬浮球拖动贴边、点一下打开；外观页与设置框同步
import assert from "node:assert";
import { start, open, P, ok } from "./helpers.mjs";
const { page, done } = await start({ width: 390, height: 844, mobile: true });
await page.waitForSelector("#cw-settings");
const S = () => page.evaluate(() => window.SillyTavern.getContext().extensionSettings.presetAtelier);
const wandShown = () => page.$eval("#cw-menu-entry", (x) => getComputedStyle(x).display !== "none");
assert.equal(await page.$("#cw-ball"), null, "默认没有悬浮球");
assert.equal(await wandShown(), true, "默认在魔棒菜单里");
assert.equal(await page.locator("[data-opt=entry]").inputValue(), "wand");
await page.evaluate(() => { const s = window.SillyTavern.getContext().extensionSettings.presetAtelier; s.floatBall = true; delete s.entry; });
await open(page, "look");
assert.equal(await page.locator(`${P("look")} [data-entry].on`).innerText(), "两个都要", "旧设置开着悬浮球时算两个都要");
await page.evaluate(() => { window.SillyTavern.getContext().extensionSettings.presetAtelier.floatBall = false; });
await page.click('#cw-root .cw-top [data-act="close"]'); await page.waitForTimeout(300);
ok("默认只有魔棒菜单；旧设置开着悬浮球时算两个都要");
await page.selectOption("[data-opt=entry]", "ball"); await page.waitForTimeout(100);
assert.ok(await page.$("#cw-ball"), "选悬浮球后出现");
assert.equal(await wandShown(), false, "只用悬浮球时魔棒菜单里不显示");
assert.equal((await S()).entry, "ball");
ok("设置框里选「悬浮球」：出现悬浮球，魔棒菜单里不显示");
await page.evaluate(() => { window.__htmlDown = 0; document.documentElement.addEventListener("mousedown", () => window.__htmlDown++); document.documentElement.addEventListener("touchstart", () => window.__htmlDown++); });
let r = await page.$eval("#cw-ball", (b) => b.getBoundingClientRect().toJSON());
await page.mouse.move(r.x + 22, r.y + 22);
await page.mouse.down();
await page.mouse.move(120, 300, { steps: 6 });
await page.mouse.up();
await page.waitForTimeout(400);
r = await page.$eval("#cw-ball", (b) => b.getBoundingClientRect().toJSON());
assert.equal(Math.round(r.x), 8, "贴到左边");
assert.equal((await S()).floatBallPos.x, 0);
assert.ok(await page.$eval("#cw-root", (x) => x.hidden).catch(() => true), "拖动不算打开");
assert.equal(await page.evaluate(() => window.__htmlDown), 0, "不触发酒馆收起抽屉");
ok("拖动后贴边并记住位置，不收起酒馆面板");
await page.click("#cw-ball"); await page.waitForTimeout(400);
assert.equal(await page.$eval("#cw-root", (x) => x.hidden), false, "点一下打开");
assert.equal(await page.$eval("#cw-ball", (b) => getComputedStyle(b).display), "none", "面板打开时隐藏");
assert.equal(await page.evaluate(() => window.__htmlDown), 0, "点球不触发酒馆收起抽屉");
ok("点一下打开面板");
await open(page, "look");
const seg = (label) => page.locator(`${P("look")} [data-entry]`, { hasText: label });
assert.equal(await page.locator(`${P("look")} .cw-sec h3`).first().innerText(), "入口", "入口在配色上面");
assert.equal(await page.locator(`${P("look")} [data-entry].on`).innerText(), "悬浮球");
await seg("两个都要").click(); await page.waitForTimeout(100);
assert.equal(await wandShown(), true, "两个都要：魔棒菜单里也有");
assert.equal(await page.locator("[data-opt=entry]").inputValue(), "both", "设置框同步");
await seg("魔棒菜单").click(); await page.waitForTimeout(100);
assert.equal(await page.$("#cw-ball"), null, "只用魔棒菜单时没有悬浮球");
assert.equal(await page.locator("[data-opt=entry]").inputValue(), "wand", "设置框同步");
ok("外观页切换入口，设置框同步");
const noteShown = (sel) => page.$eval(sel, (x) => !x.hidden && getComputedStyle(x).display !== "none");
assert.equal(await noteShown(`${P("look")} .cw-noentry`), false, "有入口时不写怎么打开");
await seg("都不要").click(); await page.waitForTimeout(100);
assert.equal(await page.$("#cw-ball"), null, "都不要：没有悬浮球");
assert.equal(await wandShown(), false, "都不要：魔棒菜单里不显示");
assert.equal((await S()).floatBall, false);
assert.equal(await page.locator("[data-opt=entry]").inputValue(), "none", "设置框同步");
assert.equal(await noteShown(`${P("look")} .cw-noentry`), true, "写出怎么打开");
assert.match(await page.textContent(`${P("look")} .cw-noentry`), /\/atelier/);
assert.equal(await noteShown("#cw-settings .cw-noentry"), true, "设置框也写");
await page.selectOption("[data-opt=entry]", "wand"); await page.waitForTimeout(100);
assert.equal(await wandShown(), true, "设置框里选回魔棒菜单");
assert.equal(await noteShown("#cw-settings .cw-noentry"), false);
assert.equal(await noteShown(`${P("look")} .cw-noentry`), false);
ok("都不要：魔棒菜单和悬浮球都没有，写出从设置框或 /atelier 打开");
await done("入口检查全部通过");
