// 配色「跟随系统」：旧设置 theme: "system" 换成开关；系统深色用夜雾，浅色用选中的配色
import assert from "node:assert";
import { start, open, P, ok } from "./helpers.mjs";
const { page, done } = await start({ width: 834, height: 1000, mobile: true, init: (p) => p.emulateMedia({ colorScheme: "light" }) });
const st = () => page.evaluate(() => {
  const s = window.SillyTavern.getContext().extensionSettings.presetAtelier;
  return { theme: s.theme, follow: s.followSystem, light: s.themeLight, applied: document.getElementById("cw-root").dataset.theme, checked: document.querySelector('[data-act="followsys"]')?.checked, pressed: document.querySelector('.cw-theme[aria-pressed="true"]')?.dataset.themeId, note: !document.querySelector('[data-r="follownote"]')?.hidden };
});
await page.evaluate(() => { window.SillyTavern.getContext().extensionSettings.presetAtelier = { theme: "system", themeLight: "taro" }; });
await open(page, "look");
let s = await st();
assert.deepEqual([s.theme, s.follow, s.light, s.applied, s.checked, s.pressed, s.note], ["taro", true, undefined, "taro", true, "taro", true]);
assert.equal(await page.locator('[data-theme-id="system"]').count(), 0, "没有「跟随系统」卡片");
ok("旧设置换成开关，浅色时用原来的配色");
await page.emulateMedia({ colorScheme: "dark" }); await page.waitForTimeout(300);
s = await st();
assert.equal(s.applied, "night", "系统深色时用夜雾");
assert.equal(s.pressed, "taro", "选中的配色不变");
ok("系统变深色，面板马上换成夜雾");
await page.click(`${P("look")} .cw-inline-switch > span`); await page.waitForTimeout(300);
s = await st();
assert.deepEqual([s.follow, s.checked, s.applied, s.note], [false, false, "taro", false]);
ok("点「跟随系统」文字也能关；关掉后深色系统下仍用选中的配色");
await page.click('[data-theme-id="bean"]'); await page.waitForTimeout(150);
await page.click(`${P("look")} .cw-inline-switch .cw-switch`); await page.waitForTimeout(300);
s = await st();
assert.deepEqual([s.theme, s.follow, s.applied], ["bean", true, "night"]);
await page.emulateMedia({ colorScheme: "light" }); await page.waitForTimeout(300);
assert.equal((await st()).applied, "bean");
ok("开关打开时换配色：浅色用新选的，深色仍是夜雾");
await done("跟随系统检查通过");
